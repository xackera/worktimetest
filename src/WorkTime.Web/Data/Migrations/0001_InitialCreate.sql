CREATE TABLE employees (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL
);

CREATE TABLE time_entries (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id integer NOT NULL REFERENCES employees (id) ON DELETE RESTRICT,
    description varchar(500) NOT NULL,
    started_at  timestamptz NOT NULL,
    ended_at    timestamptz
);

CREATE INDEX ix_time_entries_employee_started ON time_entries (employee_id, started_at);

-- У сотрудника может быть только один незавершённый таймер.
CREATE UNIQUE INDEX ux_time_entries_one_running ON time_entries (employee_id) WHERE ended_at IS NULL;
